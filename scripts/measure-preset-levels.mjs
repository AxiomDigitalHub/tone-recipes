#!/usr/bin/env node
/**
 * Level-match harness — the delivery mechanism behind any future
 * "level-matched presets" promise. We do NOT advertise the guarantee
 * until this loop runs clean across the catalog (Daniel, 2026-07-08).
 *
 * The loop:
 *   1. Render each preset's DI pass to audio/raw/<slug>.wav
 *      (Helix Native step — see scripts/AUDIO_PIPELINE.md; that step
 *      is inherently manual-ish because Helix DSP is proprietary).
 *   2. THIS SCRIPT measures every render: integrated loudness (LUFS)
 *      and true peak, via ffmpeg's EBU R128 filter.
 *   3. It reports the catalog spread and a per-preset trim in dB to
 *      hit the house target. On Helix, apply the trim on the OUTPUT
 *      block's Level parameter (it's denominated in dB, so the number
 *      transfers directly), re-render, re-measure.
 *   4. When every preset lands within the tolerance window, the
 *      guarantee is real and we can say it out loud on the site.
 *
 * Usage:
 *   node scripts/measure-preset-levels.mjs                 # full report
 *   node scripts/measure-preset-levels.mjs --target=-18    # custom target LUFS
 *   node scripts/measure-preset-levels.mjs --tolerance=1   # ± dB window
 *   node scripts/measure-preset-levels.mjs --json          # machine output
 *
 * House defaults: target -18 LUFS integrated (comfortable headroom for
 * a solo guitar stem; loud enough to compare against references),
 * tolerance ±1.0 dB, true-peak ceiling -1.0 dBTP.
 */

import { spawnSync } from "node:child_process";
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve, basename } from "node:path";

const RAW_DIR = resolve(process.cwd(), "audio/raw");
const REPORT = resolve(process.cwd(), "docs/LEVEL_MATCH_REPORT.md");

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, "").split("=");
    return [k, v ?? true];
  }),
);
const TARGET = parseFloat(args.target ?? "-18");
const TOLERANCE = parseFloat(args.tolerance ?? "1.0");
const PEAK_CEILING = -1.0;

if (!existsSync(RAW_DIR)) {
  console.error(
    `No audio/raw/ directory found. Render presets first — see scripts/AUDIO_PIPELINE.md.\n` +
      `(This harness is ready and waiting; it needs WAVs to measure.)`,
  );
  process.exit(1);
}

const wavs = readdirSync(RAW_DIR).filter((f) => f.endsWith(".wav"));
if (wavs.length === 0) {
  console.error(`audio/raw/ exists but holds no .wav files yet. Nothing to measure.`);
  process.exit(1);
}

/** Run ffmpeg's ebur128 analysis and parse integrated LUFS + true peak.
 *  ffmpeg prints the analysis summary to STDERR on success — spawnSync
 *  hands us stderr unconditionally (execFileSync only would on failure). */
function measure(path) {
  const res = spawnSync(
    "ffmpeg",
    ["-hide_banner", "-nostats", "-i", path, "-filter_complex",
      "ebur128=peak=true", "-f", "null", "-"],
    { encoding: "utf8" },
  );
  const out = res.stderr ?? "";
  const tail = out.slice(out.lastIndexOf("Summary:"));
  const lufs = parseFloat(tail.match(/I:\s*(-?[\d.]+)\s*LUFS/)?.[1] ?? "NaN");
  const peak = parseFloat(tail.match(/Peak:\s*(-?[\d.]+)\s*dBFS/)?.[1] ?? "NaN");
  return { lufs, peak };
}

const rows = [];
for (const f of wavs) {
  const slug = basename(f, ".wav");
  const { lufs, peak } = measure(resolve(RAW_DIR, f));
  const trim = Number.isNaN(lufs) ? NaN : +(TARGET - lufs).toFixed(1);
  const inWindow = Math.abs(trim) <= TOLERANCE;
  const peakOk = Number.isNaN(peak) ? false : peak <= PEAK_CEILING;
  rows.push({ slug, lufs, peak, trim, inWindow, peakOk });
}

rows.sort((a, b) => Math.abs(b.trim) - Math.abs(a.trim));
const measured = rows.filter((r) => !Number.isNaN(r.lufs));
const spread =
  measured.length > 1
    ? (Math.max(...measured.map((r) => r.lufs)) -
        Math.min(...measured.map((r) => r.lufs))).toFixed(1)
    : "0";
const passing = measured.filter((r) => r.inWindow && r.peakOk).length;

if (args.json) {
  console.log(JSON.stringify({ target: TARGET, tolerance: TOLERANCE, spread, rows }, null, 2));
  process.exit(0);
}

const lines = [];
lines.push(`# Level Match Report`);
lines.push("");
lines.push(`Generated by \`scripts/measure-preset-levels.mjs\`.`);
lines.push(`Target: **${TARGET} LUFS integrated**, window ±${TOLERANCE} dB, true-peak ceiling ${PEAK_CEILING} dBTP.`);
lines.push("");
lines.push(`**${passing} / ${measured.length} presets inside the window. Catalog spread: ${spread} dB.**`);
lines.push("");
lines.push(`| Preset | LUFS | True peak | Trim needed | In window | Peak OK |`);
lines.push(`|---|---|---|---|---|---|`);
for (const r of rows) {
  lines.push(
    `| ${r.slug} | ${r.lufs} | ${r.peak} | ${r.trim > 0 ? "+" : ""}${r.trim} dB | ${r.inWindow ? "✓" : "✗"} | ${r.peakOk ? "✓" : "✗"} |`,
  );
}
lines.push("");
lines.push(
  `Apply each trim on the preset's OUTPUT block Level (dB in HX Edit), re-render, re-run this script. ` +
    `The guarantee ships when this table is all ✓.`,
);
writeFileSync(REPORT, lines.join("\n"));
console.log(lines.slice(0, 8).join("\n"));
console.log(`\nFull table: docs/LEVEL_MATCH_REPORT.md (${rows.length} presets)`);
